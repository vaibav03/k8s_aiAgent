# ---------------------------------------------------------------------------- agent arm hook
def kc(*a, **kw):
    return lab.kubectl(*a, **kw)


def point_agent(ns: str, log) -> None:
    kc("create", "rolebinding", "kubeai-agent", "--clusterrole=kubeai-agent",
       f"--serviceaccount={AGENT_NS}:kubeai-agent", ns=ns)
    kc("annotate", "deploy/loadlab", f"kubeai.io/min-replicas={CAP_MIN}", f"kubeai.io/max-replicas={CAP_MAX}",
       "--overwrite", ns=ns)
    data = {**AGENT_CFG, "NAMESPACE": ns}
    kc("patch", "cm", "kubeai-agent-config", "--type", "merge", "-p", json.dumps({"data": data}), ns=AGENT_NS)
    kc("rollout", "restart", "deploy/kubeai-agent", ns=AGENT_NS)
    kc("rollout", "status", "deploy/kubeai-agent", "--timeout=120s", ns=AGENT_NS, timeout=150)
    log("agent pointed at", ns, json.dumps(data))


class ABRun(lab.Run):
    def deploy(self):
        super().deploy()
        if self.sc.get("ab", {}).get("arm") == "agent":
            point_agent(self.ns, self.log)

    def collect(self):
        super().collect()
        if self.sc.get("ab", {}).get("arm") != "agent":
            return
        pod = kc("get", "pods", "-l", "app.kubernetes.io/name=kubeai-agent", "-o",
                 "jsonpath={.items[0].metadata.name}", ns=AGENT_NS).stdout.strip()
        p = kc("exec", pod, "--", "cat", "/tmp/decisions.jsonl", ns=AGENT_NS, check=False, timeout=60)
        (self.dir / "decisions.jsonl").write_text(p.stdout)
        lg = kc("logs", pod, "--tail=-1", ns=AGENT_NS, check=False, timeout=60)
        (self.dir / "agent.log").write_text(lg.stdout)
        self.log("agent decision log:", len(p.stdout.splitlines()), "lines")


def run_one(path: str) -> None:
    out = ABRun(Path(path)).execute()
    sc = yaml.safe_load(Path(path).read_text())["ab"]
    dest = RUNS / sc["trial"] / sc["arm"]
    if dest.exists():
        shutil.rmtree(dest)
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.move(str(out), str(dest))
    print("moved", out, "->", dest)


def restore_agent() -> None:
    kc("patch", "cm", "kubeai-agent-config", "--type", "merge", "-p", json.dumps({"data": AGENT_RESTORE}), ns=AGENT_NS)
    kc("rollout", "restart", "deploy/kubeai-agent", ns=AGENT_NS)
    print("agent restored to observe mode in namespace default")


def run_slots(which: list[int] | None) -> None:
    write_scenarios()
    log = open(RUNS.parent / "ab.log", "a", buffering=1) if RUNS.parent.exists() else None
    for i, slot in enumerate(SLOTS, 1):
        if which and i not in which:
            continue
        msg = f"{time.strftime('%H:%M:%S')} slot {i}: {slot}"
        print(msg, flush=True)
        log and log.write(msg + "\n")
        with cf.ThreadPoolExecutor(max_workers=2) as ex:
            futs = {ex.submit(subprocess.run, [PY, __file__, "run-one", str(SCEN / f"{t}-{a}.yaml")]): (t, a)
                    for t, a in slot}
            for f in cf.as_completed(futs):
                r = f"{time.strftime('%H:%M:%S')} slot {i} {futs[f]} rc={f.result().returncode}"
                print(r, flush=True)
                log and log.write(r + "\n")
    restore_agent()


