    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import numpy as np
    colors = {"agent": "#1f6feb", "hpa30": "#d4762c", "hpa300": "#7a7a7a"}
    (HERE / "plots").mkdir(exist_ok=True)
    for trial in TRIALS:
        arms = [a for a in ARMS if (trial, a) in tl]
        if not arms:
            continue
        fig, ax = plt.subplots(3, 1, figsize=(11, 8.5), sharex=True)
        for a in arms:
            rel, rd, rr, p95, rps, err, faults, acts = tl[(trial, a)]
            ax[0].step(rel, rd, where="post", color=colors[a], label=f"{a} desired", lw=1.8)
